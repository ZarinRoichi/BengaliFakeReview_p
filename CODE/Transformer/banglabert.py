# ✅ Function to compute accuracy, precision, recall, and F1-score (Fake & Non-Fake Separately)
def compute_metrics(eval_pred):
    logits, labels = eval_pred  # Extract model outputs
    predictions = np.argmax(logits, axis=-1)  # Convert logits to class predictions

    # ✅ Compute accuracy
    acc = accuracy_score(labels, predictions)
    precision, recall, f1, _ = precision_recall_fscore_support(labels, predictions, average="binary")

    # ✅ Compute Fake vs Non-Fake metrics separately
    report = classification_report(labels, predictions, target_names=["Non-Fake", "Fake"], digits=4, output_dict=True)

    # Extract per-class F1-scores
    fake_f1 = report["Fake"]["f1-score"]
    non_fake_f1 = report["Non-Fake"]["f1-score"]
    weighted_f1 = report["weighted avg"]["f1-score"]

    return {
        "accuracy": acc,
        "Fake F1-score": fake_f1,
        "Non-Fake F1-score": non_fake_f1,
        "Weighted F1-score": weighted_f1
    }

