# ✅ Take User Input for Model Evaluation Results
print("\n🔹 Enter evaluation metrics for each model (values between 0 and 1) 🔹")

models = ["BanglaBERT", "XLM-R", "mBERT"]
metrics = ["Accuracy", "Precision", "Recall", "F1-score"]
user_results = {}

for model in models:
    print(f"\n🟢 Enter values for {model}:")
    user_results[model] = {}
    for metric in metrics:
        while True:
            try:
                value = float(input(f"{metric} (0-1) for {model}: ")) * 100  # Convert to percentage
                if 0 <= value <= 100:
                    user_results[model][metric] = value
                    break
                else:
                    print("❌ Invalid input. Enter a value between 0 and 1.")
            except ValueError:
                print("❌ Invalid input. Please enter a number.")

# ✅ Convert user input into a structured NumPy array for visualization
data = np.array([
    [user_results["BanglaBERT"]["Accuracy"], user_results["BanglaBERT"]["Precision"],
     user_results["BanglaBERT"]["Recall"], user_results["BanglaBERT"]["F1-score"]],

    [user_results["XLM-R"]["Accuracy"], user_results["XLM-R"]["Precision"],
     user_results["XLM-R"]["Recall"], user_results["XLM-R"]["F1-score"]],

    [user_results["mBERT"]["Accuracy"], user_results["mBERT"]["Precision"],
     user_results["mBERT"]["Recall"], user_results["mBERT"]["F1-score"]],
])

# ✅ Function to plot accuracy comparison
def plot_accuracy():
    plt.figure(figsize=(6, 4))
    plt.plot(models, data[:, 0], marker="o", linestyle="-", color="blue", linewidth=2, markersize=8)
    plt.xlabel("Models")
    plt.ylabel("Accuracy (%)")
    plt.title("Accuracy Comparison Across Models")
    plt.ylim(50, 100)
    plt.grid(True, linestyle="--", alpha=0.7)
    plt.show()

# ✅ Function to plot heatmap of evaluation metrics
def plot_heatmap():
    plt.figure(figsize=(6, 4))
    sns.heatmap(data, annot=True, cmap="coolwarm", xticklabels=metrics, yticklabels=models, fmt=".1f")
    plt.xlabel("Metrics")
    plt.ylabel("Models")
    plt.title("Model Performance Heatmap")
    plt.show()

# ✅ Function to plot radar chart (Spider Chart) with adjusted text placement
def plot_radar_chart():
    angles = np.linspace(0, 2 * np.pi, len(metrics), endpoint=False).tolist()
    angles += angles[:1]  # Closing the circle

    fig, ax = plt.subplots(figsize=(7, 7), subplot_kw=dict(polar=True))  # ✅ Increase figure size

    for i, model in enumerate(models):
        values = list(data[i]) + [data[i][0]]  # Repeat first value at end
        ax.plot(angles, values, label=model, linewidth=2)
        ax.fill(angles, values, alpha=0.1)

    # ✅ Fix text overlap by increasing padding
    ax.set_xticks(angles[:-1])
    ax.set_xticklabels(metrics, fontsize=12, fontweight="bold", rotation=15)  # ✅ Rotate labels slightly

    plt.title("Performance Comparison of Models", fontsize=14, fontweight="bold", pad=20)  # ✅ Adjust title spacing
    plt.legend(loc="upper right", bbox_to_anchor=(1.2, 1.1))  # ✅ Move legend outside plot
    plt.show()

# ✅ Run the improved radar chart
plot_radar_chart()


# ✅ Run Plots
